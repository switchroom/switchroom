#!/usr/bin/env node
/**
 * check-agent-attribution-trailers — a machine-written commit must say WHICH
 * machine wrote it.
 *
 * Why this script exists
 * ----------------------
 * Every commit in this repo is authored by the operator's GitHub account,
 * because switchroom agents commit with the operator's git identity. That is
 * deliberate and stays. The cost is that `git log` cannot answer "which agent,
 * on which model, produced this" — the only machine marker is the generic
 * `Co-authored-by: Claude ...` trailer, which names no agent and no model.
 *
 * `bin/git-agent-attribution-hook.sh` (installed as a global
 * `prepare-commit-msg` hook in every agent container) writes the missing
 * facts:
 *
 *   Switchroom-Agent: klanker
 *   Switchroom-Model: claude-opus-5
 *
 * The hook is the mechanism. THIS script is the alarm that fires when the
 * mechanism did not run — a container booted from an image built before the
 * hook existed, an agent that unset `core.hooksPath`, a commit made through a
 * path that never reached the hook. Without the alarm, absence of attribution
 * is silent by construction, which is exactly the failure mode the trailers
 * exist to end.
 *
 * ── THE RULE (and why a human at a laptop is never blocked) ──────────────
 *
 * There is no intrinsic bit on a commit that says "a container made this":
 * author and committer are the operator either way. So we key off the marker
 * the MODEL writes, which is independent of the hook the ENVIRONMENT writes:
 *
 *   A commit is MACHINE-AUTHORED iff it carries a `Co-authored-by:` trailer
 *   naming Claude/Anthropic, OR it already carries one of the two
 *   `Switchroom-*` trailers.
 *
 *   A machine-authored commit MUST carry BOTH `Switchroom-Agent:` and
 *   `Switchroom-Model:`, each non-empty and well-shaped.
 *
 *   A commit with neither marker is a human commit. It is never inspected and
 *   can never fail. A contributor committing by hand from a laptop has no
 *   `Co-authored-by: Claude` trailer and no `Switchroom-*` trailers, so this
 *   check is a no-op for them.
 *
 * The two producers are deliberately kept separate — the model writes
 * `Co-authored-by`, the hook writes `Switchroom-*` — precisely so that
 * disabling the hook cannot also erase the evidence of its own absence. If
 * the hook emitted `Co-authored-by` too, a bypassed hook would produce a
 * commit with no markers at all and this check could never go red. See the
 * "NOT ADDED HERE" section of `bin/git-agent-attribution-hook.sh`.
 *
 * RESIDUAL GAP, stated plainly: a machine commit that drops BOTH markers is
 * indistinguishable from a human commit and passes. Closing that would need a
 * distinct committer identity, which would change who GitHub shows as the
 * committer — an explicit non-goal. The hook is what makes the markers
 * present; this check is the backstop, not the primary guarantee.
 *
 * ── Scope ────────────────────────────────────────────────────────────────
 *
 * Only commits in the current branch's range (`merge-base(base, HEAD)..HEAD`)
 * are inspected — never repo history. Backfill is out of scope by design.
 * Merge commits are skipped (their message is generated by git, and the
 * attribution lives in the merged commits). Commits committed before
 * ENFORCEMENT_START are exempt: the hook only reaches an agent container after
 * the agent image is rebuilt and the fleet restarted, so commits from before
 * that rollout could not have been stamped.
 *
 * If the base ref cannot be resolved (a shallow clone, a detached checkout
 * with no `origin/main`), the check SKIPS with a note rather than failing.
 * Blocking a developer because their clone is shallow would be a false
 * positive, and CI checks out with `fetch-depth: 0` for exactly this reason
 * (`.github/workflows/agent-attribution.yml`, and `ci-lint.yml`'s `lint-run`).
 *
 * Genuine exceptions (e.g. replaying an upstream patch verbatim) go in
 * `scripts/check-agent-attribution-trailers-allowlist.txt`, one full 40-char
 * SHA per line — a deliberate, reviewable edit, same ratchet shape as the
 * sibling guards.
 *
 * Run: `npm run lint:agent-attribution-trailers` (also part of `npm run lint`).
 */

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Commits committed before this instant are exempt.
 *
 * Set to one week after the PR that introduces the hook, because the hook
 * lands in an agent container only after `docker/Dockerfile.agent` is rebuilt
 * AND that agent is restarted. Enforcing from the merge commit onwards would
 * red every agent PR opened during the rollout window for a mechanism that
 * demonstrably was not yet installed. It is a fixed instant, not a rolling
 * window, so it retires itself.
 */
export const ENFORCEMENT_START = Date.parse('2026-08-05T00:00:00Z')

const ALLOWLIST_REL = 'scripts/check-agent-attribution-trailers-allowlist.txt'

/** Trailer tokens this guard is about. Case-insensitive, per git's own rules. */
export const AGENT_TRAILER = 'Switchroom-Agent'
export const MODEL_TRAILER = 'Switchroom-Model'

/** Shape gate for an agent slug — mirrors switchroom's own agent-name rules. */
const AGENT_VALUE_RE = /^[A-Za-z0-9][A-Za-z0-9._-]{0,62}$/
/** Shape gate for a model id — permissive enough for `openrouter/z-ai/glm-5.2`. */
const MODEL_VALUE_RE = /^[A-Za-z0-9][A-Za-z0-9._@:+/-]{0,99}$/

/**
 * Parse ONE paragraph (a run of non-blank lines) into trailers.
 *
 * Continuation lines (leading whitespace) fold into the previous trailer, per
 * git's own rule. Returns `null` — not `[]` — when the paragraph contains any
 * line that is neither a `Token: value` trailer nor a continuation: that
 * distinction is load-bearing for the caller, which treats a prose-bearing
 * paragraph as a hard stop rather than an empty result.
 *
 * @param {string[]} block lines of a single paragraph
 * @returns {{token: string, value: string}[] | null}
 */
function parseParagraph(block) {
  /** @type {{token: string, value: string}[]} */
  const out = []
  for (const line of block) {
    if (/^\s/.test(line) && out.length > 0) {
      // Continuation of the previous trailer.
      out[out.length - 1].value += ` ${line.trim()}`
      continue
    }
    const m = /^([A-Za-z0-9][A-Za-z0-9-]*)\s*:\s?(.*)$/.exec(line)
    if (!m) return null
    out.push({ token: m[1], value: m[2].trim() })
  }
  return out
}

/**
 * Pull the trailer block out of a raw commit message.
 *
 * Implemented here rather than shelling to `git interpret-trailers --parse`
 * per commit: this is a hot loop over a PR's commits and the parse is the
 * same well-defined "last paragraph of `Token: value` lines" git uses.
 *
 * GitHub's squash-merge reparagraphs trailers: it collects the
 * `Co-authored-by:` lines and re-emits them as a SEPARATE final paragraph,
 * split from the `Switchroom-*` trailers the source commit carried by a blank
 * line. Reading only the final paragraph then sees the Claude co-author but
 * not the attribution that sits one paragraph above it, and the guard reds a
 * fully-attributed PR (issue seen on #4381's squash `bb793cb`). So when the
 * final paragraph is entirely trailer lines, fold in each IMMEDIATELY-
 * PRECEDING paragraph that is ITSELF entirely trailer lines, treating the run
 * of consecutive trailer-only paragraphs as one logical trailer block.
 *
 * Folding STOPS at the first paragraph carrying any non-trailer (prose) line.
 * That preserves the original "a stray prose line means the hook did not run →
 * no trailer block" detection: a prose separator (e.g. a `---------` line, or
 * a PR-description paragraph) between the `Switchroom-*` trailers and a
 * `Co-authored-by: Claude` final block still isolates them, so such a commit
 * still fails. Folding only ADDS genuinely-present adjacent trailers into
 * view; a truly unattributed commit has nothing to fold and still fails.
 *
 * @param {string} message raw commit message (subject + body)
 * @returns {{token: string, value: string}[]}
 */
export function parseTrailers(message) {
  const lines = String(message).replace(/\r\n/g, '\n').split('\n')
  // Drop trailing blank lines.
  let end = lines.length
  while (end > 0 && lines[end - 1].trim() === '') end--
  if (end === 0) return []

  /** @type {{token: string, value: string}[]} */
  const folded = []
  let cursor = end
  let isFinal = true
  while (cursor > 0) {
    // Skip the blank line(s) separating this paragraph from the next.
    let pEnd = cursor
    while (pEnd > 0 && lines[pEnd - 1].trim() === '') pEnd--
    if (pEnd === 0) break
    let pStart = pEnd
    while (pStart > 0 && lines[pStart - 1].trim() !== '') pStart--

    const parsed = parseParagraph(lines.slice(pStart, pEnd))
    if (parsed === null) {
      // A prose-bearing paragraph. If it IS the final paragraph, git treats
      // the message as having no trailer block at all — the "hook did not run"
      // case. If it merely precedes a trailer-only run, it is the stop line.
      return isFinal ? [] : folded
    }
    // This paragraph precedes what we have collected, so prepend it.
    folded.unshift(...parsed)
    cursor = pStart
    isFinal = false
  }
  return folded
}

/** @param {{token: string, value: string}[]} trailers @param {string} token */
function trailerValues(trailers, token) {
  const want = token.toLowerCase()
  return trailers.filter((t) => t.token.toLowerCase() === want).map((t) => t.value)
}

/**
 * Is this commit machine-authored? See "THE RULE" above.
 *
 * @param {{token: string, value: string}[]} trailers
 * @returns {boolean}
 */
export function isMachineAuthored(trailers) {
  const coAuthored = trailerValues(trailers, 'Co-authored-by')
  if (coAuthored.some((v) => /claude|anthropic/i.test(v))) return true
  // A half-written Switchroom-* pair is machine work too — and is exactly
  // the case a `Co-authored-by`-only rule would miss.
  if (trailerValues(trailers, AGENT_TRAILER).length > 0) return true
  if (trailerValues(trailers, MODEL_TRAILER).length > 0) return true
  return false
}

/**
 * Verdict for one commit. Pure — the CLI and the tests share it.
 *
 * @param {{sha: string, message: string, committedAtMs: number}} commit
 * @returns {{ok: true, reason: string} | {ok: false, problems: string[]}}
 */
export function checkCommit(commit) {
  if (Number.isFinite(commit.committedAtMs) && commit.committedAtMs < ENFORCEMENT_START) {
    return { ok: true, reason: 'predates ENFORCEMENT_START' }
  }
  const trailers = parseTrailers(commit.message)
  if (!isMachineAuthored(trailers)) {
    return { ok: true, reason: 'human commit (no machine marker)' }
  }

  /** @type {string[]} */
  const problems = []

  const agents = trailerValues(trailers, AGENT_TRAILER)
  if (agents.length === 0) {
    problems.push(`missing \`${AGENT_TRAILER}:\` trailer`)
  } else if (!AGENT_VALUE_RE.test(agents[0])) {
    problems.push(`\`${AGENT_TRAILER}: ${agents[0]}\` is not a valid agent slug`)
  }

  const models = trailerValues(trailers, MODEL_TRAILER)
  if (models.length === 0) {
    problems.push(`missing \`${MODEL_TRAILER}:\` trailer`)
  } else if (!MODEL_VALUE_RE.test(models[0])) {
    problems.push(`\`${MODEL_TRAILER}: ${models[0]}\` is not a valid model id`)
  }

  return problems.length === 0
    ? { ok: true, reason: 'attributed' }
    : { ok: false, problems }
}

// ── git plumbing ─────────────────────────────────────────────────────────

/** @param {string[]} args @param {string} cwd */
function git(args, cwd) {
  return execFileSync('git', args, { cwd, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'pipe'] })
}

/**
 * Resolve the commit range to inspect.
 *
 * @param {string} cwd
 * @returns {{base: string, head: string} | null} null ⇒ unresolvable, skip
 */
export function resolveRange(cwd, env = process.env) {
  const head = env.AGENT_ATTRIBUTION_HEAD || 'HEAD'
  const candidates = [
    env.AGENT_ATTRIBUTION_BASE,
    // GitHub Actions `pull_request`: the target branch, already fetched when
    // the workflow checks out with fetch-depth: 0.
    env.GITHUB_BASE_REF ? `origin/${env.GITHUB_BASE_REF}` : undefined,
    'origin/main',
    'main',
  ].filter(Boolean)

  for (const c of candidates) {
    try {
      git(['rev-parse', '--verify', '--quiet', `${c}^{commit}`], cwd)
      git(['merge-base', c, head], cwd)
      return { base: c, head }
    } catch {
      /* try the next candidate */
    }
  }
  return null
}

// ASCII unit / record separators. A commit message can contain literally any
// printable delimiter you were about to pick; these two cannot appear in one,
// and git emits them for us via %x1f / %x1e.
const FIELD = '\x1f'
const RECORD = '\x1e'

/**
 * Read every non-merge commit in `base..head`.
 *
 * @param {string} cwd
 * @param {{base: string, head: string}} range
 * @returns {{sha: string, message: string, committedAtMs: number}[]}
 */
export function readCommits(cwd, range) {
  const raw = git(
    [
      'rev-list',
      '--no-merges',
      '--format=%H%x1f%ct%x1f%B%x1e',
      `${range.base}..${range.head}`,
    ],
    cwd,
  )
  /** @type {{sha: string, message: string, committedAtMs: number}[]} */
  const out = []
  for (const chunk of raw.split(RECORD)) {
    // `rev-list --format` emits a `commit <sha>` header line before each
    // formatted record; strip it.
    const body = chunk.replace(/^\s*commit [0-9a-f]{4,40}\n/m, '').trim()
    if (!body) continue
    const parts = body.split(FIELD)
    if (parts.length < 3) continue
    out.push({
      sha: parts[0].trim(),
      committedAtMs: Number(parts[1].trim()) * 1000,
      message: parts.slice(2).join(FIELD),
    })
  }
  return out
}

/**
 * The git toplevel containing `dir`, or `dir` itself when it is not a repo.
 *
 * The guard inspects the repo it is RUN IN, not the repo it lives in: that is
 * what lets the outcome tests point it at a throwaway fixture and assert the
 * real exit code. Falling back to `repoRoot` would make every fixture case
 * silently grade this repo instead.
 *
 * @param {string} dir
 */
function resolveRepoRoot(dir) {
  try {
    return git(['rev-parse', '--show-toplevel'], dir).trim() || dir
  } catch {
    return dir
  }
}

/** @param {string} root */
function loadAllowlist(root) {
  const p = resolve(root, ALLOWLIST_REL)
  if (!existsSync(p)) return new Set()
  return new Set(
    readFileSync(p, 'utf-8')
      .split('\n')
      .map((l) => l.replace(/#.*$/, '').trim())
      .filter((l) => l.length > 0),
  )
}

/**
 * @param {string} cwd
 * @returns {{status: 'pass'|'skip'|'fail', lines: string[]}}
 */
export function run(cwd = resolveRepoRoot(process.cwd()), env = process.env) {
  const range = resolveRange(cwd, env)
  if (!range) {
    return {
      status: 'skip',
      lines: [
        'check-agent-attribution-trailers: SKIP — no base ref to diff against.',
        '  Tried $AGENT_ATTRIBUTION_BASE, origin/$GITHUB_BASE_REF, origin/main, main.',
        '  A shallow clone has no base; CI checks out with fetch-depth: 0.',
      ],
    }
  }

  const allowlist = loadAllowlist(cwd)
  const commits = readCommits(cwd, range)
  /** @type {string[]} */
  const failures = []
  let inspected = 0
  // Counted separately so the OK line never reads "0 machine-authored" for a
  // branch that IS fully attributed and merely predates the rollout instant —
  // that reads like the guard found nothing to check, which is the exact
  // false-comfort this guard exists to remove.
  let grace = 0

  for (const c of commits) {
    if (allowlist.has(c.sha)) continue
    const verdict = checkCommit(c)
    if (verdict.ok) {
      if (verdict.reason === 'attributed') inspected++
      if (verdict.reason === 'predates ENFORCEMENT_START') grace++
      continue
    }
    inspected++
    const subject = c.message.split('\n')[0]
    failures.push(`  ${c.sha.slice(0, 12)} ${subject}`)
    for (const p of verdict.problems) failures.push(`      → ${p}`)
  }

  if (failures.length > 0) {
    return {
      status: 'fail',
      lines: [
        'check-agent-attribution-trailers: FAIL',
        '',
        `These commits in ${range.base}..${range.head} were written by a model but do not say`,
        'which agent or which model produced them:',
        '',
        ...failures,
        '',
        'Expected on every machine-authored commit:',
        `  ${AGENT_TRAILER}: <agent slug>`,
        `  ${MODEL_TRAILER}: <model id>`,
        '',
        'These are written automatically by the global `prepare-commit-msg` hook',
        '(bin/git-agent-attribution-hook.sh) inside every switchroom agent container.',
        'Seeing this means the hook did not run. Usual causes:',
        '  - the container is running an agent image built before the hook existed',
        '    → rebuild the agent image and restart the agent;',
        '  - `git config --global core.hooksPath` is unset or points elsewhere',
        '    → `git config --global core.hooksPath /opt/switchroom/git-hooks`;',
        '  - the commits were made outside a container.',
        '',
        'To fix commits already made, re-run the hook over them:',
        '  git rebase -i --exec \'git commit --amend --no-edit\' ' + range.base,
        '',
        `Genuine exceptions go in ${ALLOWLIST_REL} (one full SHA per line, with a reason).`,
      ],
    }
  }

  return {
    status: 'pass',
    lines: [
      `check-agent-attribution-trailers: OK — ${commits.length} commit(s) in ${range.base}..${range.head}, ` +
        `${inspected} machine-authored and attributed` +
        (grace > 0
          ? `, ${grace} exempt (committed before ENFORCEMENT_START ` +
            `${new Date(ENFORCEMENT_START).toISOString()}).`
          : '.'),
    ],
  }
}

// ── CLI ──────────────────────────────────────────────────────────────────

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
if (isMain) {
  const result = run()
  const sink = result.status === 'fail' ? console.error : console.log
  for (const l of result.lines) sink(l)
  process.exit(result.status === 'fail' ? 1 : 0)
}
